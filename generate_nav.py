#!/usr/bin/env python3
"""扫描账号下所有启用了 GitHub Pages 的公开仓库，生成导航 index.html。"""
import html as html_mod
import json
import os
import sys
from datetime import datetime, timedelta, timezone
import urllib.error
import urllib.request

try:
    from zoneinfo import ZoneInfo, ZoneInfoNotFoundError
except ImportError:  # pragma: no cover - Python < 3.9
    ZoneInfo = None

    class ZoneInfoNotFoundError(KeyError):
        pass

API = "https://api.github.com"
DEFAULT_TZ = "Asia/Shanghai"
MAX_PAGES = 50  # 翻页上限（最多 5000 个仓库），防止 API 异常时无限翻页
DESC_LIMIT = 120  # 卡片描述最大字符数

# 控制台编码（如 Windows 的 GBK）无法表示部分符号时用 ASCII 兜底，避免打印日志本身导致崩溃。
sys.stdout.reconfigure(errors="replace")
sys.stderr.reconfigure(errors="replace")

STRINGS = {
    "zh-CN": {
        "lang": "zh-CN",
        "no_desc": "（无描述）",
        "repo_label": "仓库：",
        "updated_label": "更新：",
        "updated_unknown": "未知",
        "empty": "暂未发现启用了 GitHub Pages 的公开仓库",
        "title": "{owner} 的 GitHub Pages 导航",
        "meta": "共 {n} 个站点 · 自动更新于 {t}",
        "footer": "由 GitHub Action 自动生成 · 每日扫描更新",
    },
    "en": {
        "lang": "en",
        "no_desc": "(no description)",
        "repo_label": "repo: ",
        "updated_label": "updated: ",
        "updated_unknown": "unknown",
        "empty": "No public repos with GitHub Pages enabled yet.",
        "title": "{owner}'s GitHub Pages navigation",
        "meta": "{n} sites · auto-updated {t}",
        "footer": "Auto-generated by GitHub Action · scanned daily",
    },
}


def strings():
    lang = os.environ.get("LANG", "").split(".")[0].replace("_", "-")
    if lang.startswith("en"):
        return STRINGS["en"]
    return STRINGS["zh-CN"]


def fixed_offset(tz_name):
    """ZoneInfo 不可用时的兜底偏移。

    只认识 Chinese Standard Time 这一种情况；其它无法识别的时区明确回退 UTC 并由调用方告警，
    而不是靠字符串包含关系瞎猜（例如 "America/New_York" 曾因此被当成 UTC）。
    """
    if ZoneInfo:
        try:
            return datetime.now(ZoneInfo(tz_name)).utcoffset()
        except (ZoneInfoNotFoundError, ValueError, OSError):
            pass
    if tz_name in ("Asia/Shanghai", "Asia/Chongqing", "Asia/Urumqi", "Asia/Harbin", "PRC", "Asia/Taipei"):
        return timedelta(hours=8)
    print(
        f"警告: 时区 {tz_name!r} 无法解析（缺少 tzdata？），已回退 UTC",
        file=sys.stderr,
    )
    return timedelta(0)


def now_in_tz(tz_name):
    if ZoneInfo:
        try:
            return datetime.now(ZoneInfo(tz_name))
        except (ZoneInfoNotFoundError, ValueError, OSError):
            pass
    return datetime.now(timezone(fixed_offset(tz_name)))


class ApiError(Exception):
    """GitHub API request failed (HTTP error, network error or bad JSON)."""

    def __init__(self, status, path, detail=""):
        super().__init__(f"{status} {path} {detail}".strip())
        self.status = status
        self.path = path
        self.detail = detail


def api_get(path, token=None):
    req = urllib.request.Request(
        f"{API}{path}",
        headers={"Accept": "application/vnd.github+json", "User-Agent": "github-pages-nav"},
    )
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            return resp.status, json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise ApiError(e.code, path, e.reason) from e
    except (urllib.error.URLError, TimeoutError, OSError) as e:
        raise ApiError("network", path, str(e)) from e
    except ValueError as e:
        raise ApiError("invalid-json", path, str(e)) from e


def list_public_repos(owner, token):
    repos = []
    page = 1
    while page <= MAX_PAGES:
        try:
            code, data = api_get(
                f"/users/{owner}/repos?type=owner&sort=pushed&direction=desc&per_page=100&page={page}",
                token,
            )
        except ApiError as e:
            # 第一页失败绝不能让调用方误以为“没有仓库”；后续页失败则返回已拿到的部分。
            if page == 1:
                raise
            print(f"警告: 获取第 {page} 页仓库失败，结果可能不完整: {e}", file=sys.stderr)
            break
        if code != 200 or not data:
            if page == 1:
                raise ApiError(f"unexpected-status-{code}", f"/users/{owner}/repos", "empty or non-200 response")
            print(f"警告: 第 {page} 页响应异常，结果可能不完整", file=sys.stderr)
            break
        repos.extend(data)
        if len(data) < 100:
            break
        page += 1
    return repos


def collect_entries(owner, token):
    """返回 (通过 Pages 检查的条目, 未完整获取/无法检查的仓库全名列表)。"""
    entries = []
    failed = []
    repos = list_public_repos(owner, token)
    if len(repos) >= MAX_PAGES * 100:
        failed.append(f"<超过 {MAX_PAGES} 页上限，后续仓库未扫描>")
    for r in repos:
        full = r["full_name"]
        try:
            code, data = api_get(f"/repos/{full}/pages", token)
        except ApiError as e:
            # 404 = 没有 Pages；其它错误不代表没有 Pages，记为失败并跳过，避免悄悄从页面消失。
            if e.status == 404:
                print(f"  - {full} (无 Pages)")
                continue
            failed.append(full)
            print(f"  ! {full} (检查 Pages 失败，已跳过): {e}", file=sys.stderr)
            continue
        if code == 200 and data:
            entries.append({
                "name": r["name"],
                "description": r.get("description") or "",
                "repo_url": r["html_url"],
                "pages_url": data.get("html_url") or f"https://{owner}.github.io/{r['name']}/",
                "updated": (r.get("pushed_at") or "")[:10],
            })
            print(f"  ✓ {full}")
        else:
            print(f"  - {full} (无 Pages)")
    return entries, failed


def esc(s):
    return html_mod.escape(s or "", quote=True)


def clean_desc(s):
    """把描述压成单行并截断到 DESC_LIMIT，避免撑坏卡片布局。"""
    text = " ".join((s or "").split())
    if len(text) > DESC_LIMIT:
        text = text[: DESC_LIMIT - 1].rstrip() + "…"
    return text


def card_html(e, s):
    desc = clean_desc(e["description"]) or s["no_desc"]
    return f"""    <div class="card">
      <a class="name" href="{esc(e['pages_url'])}" target="_blank" rel="noopener">{esc(e['name'])}</a>
      <div class="desc">{esc(desc)}</div>
      <div class="pages">{s['repo_label']}<a href="{esc(e['repo_url'])}" target="_blank" rel="noopener">{esc(e['repo_url'])}</a></div>
      <div class="updated">{s['updated_label']}{esc(e['updated']) or s['updated_unknown']}</div>
    </div>"""


def render(owner, entries, avatar_url=None):
    s = strings()
    cards = "\n".join(card_html(e, s) for e in entries)
    body = (
        f'<div class="grid">\n{cards}\n  </div>'
        if entries
        else f'<div class="empty">{s["empty"]}</div>'
    )
    tz_name = os.environ.get("TIMEZONE", DEFAULT_TZ)
    updated_at = now_in_tz(tz_name).strftime("%Y-%m-%d %H:%M") + f" ({tz_name})"
    favicon = (
        f'<link rel="icon" href="{esc(avatar_url)}">\n'
        f'<link rel="apple-touch-icon" href="{esc(avatar_url)}">'
        if avatar_url else ""
    )
    title = s["title"].format(owner=esc(owner))
    meta = s["meta"].format(n=len(entries), t=esc(updated_at))
    return f"""<!DOCTYPE html>
<html lang="{s['lang']}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
{favicon}
<title>{title}</title>
<style>
:root {{ --bg:#0d1117; --card:#161b22; --border:#30363d; --text:#c9d1d9; --muted:#8b949e; --accent:#58a6ff; }}
* {{ box-sizing:border-box; }}
body {{ margin:0; background:var(--bg); color:var(--text); font-family:-apple-system,"Segoe UI",Roboto,"PingFang SC","Microsoft YaHei",sans-serif; }}
header {{ padding:2rem 1rem 1rem; max-width:1100px; margin:0 auto; }}
h1 {{ font-size:1.5rem; margin:0 0 .25rem; }}
.meta {{ color:var(--muted); font-size:.9rem; }}
main {{ max-width:1100px; margin:0 auto; padding:1rem; }}
.grid {{ display:grid; grid-template-columns:repeat(auto-fill,minmax(280px,1fr)); gap:1rem; }}
.card {{ background:var(--card); border:1px solid var(--border); border-radius:8px; padding:1rem; display:flex; flex-direction:column; transition:transform .15s, border-color .15s; }}
.card:hover {{ transform:translateY(-2px); border-color:var(--accent); }}
.name {{ font-weight:600; color:var(--accent); text-decoration:none; font-size:1.05rem; word-break:break-all; }}
.desc {{ color:var(--muted); font-size:.875rem; margin:.5rem 0; flex:1; line-height:1.5; display:-webkit-box; -webkit-line-clamp:3; -webkit-box-orient:vertical; overflow:hidden; }}
.pages {{ font-size:.8rem; color:var(--text); word-break:break-all; }}
.pages a {{ color:var(--accent); text-decoration:none; }}
.updated {{ color:var(--muted); font-size:.75rem; margin-top:.5rem; }}
.empty {{ color:var(--muted); text-align:center; padding:3rem; }}
footer {{ max-width:1100px; margin:0 auto; padding:1rem; color:var(--muted); font-size:.8rem; }}
</style>
</head>
<body>
<header>
  <h1>{title}</h1>
  <div class="meta">{meta}</div>
</header>
<main>
{body}
</main>
<footer>{s['footer']}</footer>
</body>
</html>
"""


def main():
    owner = os.environ.get("OWNER") or os.environ.get("GITHUB_REPOSITORY_OWNER")
    if not owner:
        repo_env = os.environ.get("GITHUB_REPOSITORY", "")
        owner = repo_env.split("/")[0] if "/" in repo_env else ""
    if not owner:
        print("无法确定 owner（设置 OWNER 或 GITHUB_REPOSITORY 环境变量）", file=sys.stderr)
        sys.exit(1)

    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_PAT")

    avatar_url = None
    try:
        code, data = api_get(f"/users/{owner}", token)
    except ApiError as e:
        print(f"警告: 获取头像失败，忽略: {e}", file=sys.stderr)
        code, data = 0, None
    if code == 200 and data:
        avatar_url = data.get("avatar_url")
        print(f"头像: {avatar_url}")

    print(f"扫描 {owner} 的公开仓库...")
    try:
        entries, failed = collect_entries(owner, token)
    except ApiError as e:
        # 拿不到仓库列表时绝不能覆盖已有的 index.html，否则会把导航页清空。
        print(f"错误: 无法列出仓库，未写入 index.html: {e}", file=sys.stderr)
        sys.exit(1)

    entries.sort(key=lambda e: e["updated"], reverse=True)
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "index.html")
    with open(out, "w", encoding="utf-8") as f:
        f.write(render(owner, entries, avatar_url))
    print(f"生成 {len(entries)} 个条目 -> {out}")
    if failed:
        print(f"警告: {len(failed)} 个仓库因 Pages 检查失败未包含: {', '.join(failed)}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
